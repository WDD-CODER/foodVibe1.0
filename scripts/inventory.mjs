/**
 * The inventory: a short list of what already exists (families, engine classes, tokens), generated from the code so
 * agents read it instead of searching.
 *
 *   node scripts/inventory.mjs [--check] [--config <json file>]
 *
 * Writes `paths.inventory` (default docs/brain/inventory.md): a header line, then one block per section —
 *   ## Families        id · selector · when, from the registry (`paths.reuseRegistry`)
 *   ## Engine classes  the class selectors that start with `reuse.enginePrefix` in `reuse.globalStylesheet`
 *   ## Tokens          the token definitions in `styleqa.tokenFiles`, grouped by the `styleqa.tokenPrefixes` kinds
 *   ## Defaults (on)   id — rule — piece for each product default that is `on` (`paths.productDefaults`)
 * A section with nothing in it is left out (an empty setting = that section off). Under 150 lines: a long block ends
 * with `+N more`. The order is fixed, so two runs give the same bytes. Sections are pluggable: `sections` is an array of
 * { id, title, build(ctx) → [{ heading?, items, pack? }] } and a later plan adds its own.
 * --check compares the committed file with what the code gives: `INVENTORY: ok` (exit 0) or
 * `INVENTORY: stale — run node scripts/inventory.mjs` (exit 1). --config <file> is a JSON object laid over the settings
 * (tests); it may hold the keys at top level or under "inventory".
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, realpathSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import picomatch from 'picomatch'
import { readRegistryFile } from './lib/registry.mjs'
import { readContract, onLines } from './lib/product-defaults.mjs'

/** The project settings, rendered from kit.config.json. */
export const INVENTORY_CONFIG = {
  path: "docs/brain/inventory.md" || 'docs/brain/inventory.md',
  registry: "docs/brain/component-families.md" || 'docs/brain/component-families.md',
  defaults: "_shared/product-defaults.md" || 'docs/project/product-defaults.md',
  globalStylesheet: "src/styles.scss" || '',
  enginePrefix: "c-" || '',
  tokenKinds: { color: "--color-", fontSize: "--fs-", radius: "--radius-" },
  tokenFiles: ["src/styles.scss"],
}

export const MAX_LINES = 150
const HEADER = ['# Inventory', '', 'Generated by node scripts/inventory.mjs — do not edit']
const WIDTH = 110

/** The settings with an override object laid over them (nested tokenKinds merged by key). */
export function inventoryConfig(over = {}) {
  const o = over?.inventory && typeof over.inventory === 'object' ? over.inventory : over ?? {}
  return { ...INVENTORY_CONFIG, ...o, tokenKinds: { ...INVENTORY_CONFIG.tokenKinds, ...(o.tokenKinds ?? {}) } }
}

const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

/** Repo files (tracked and untracked, not ignored), sorted; falls back to nothing when git is unavailable. */
function repoFiles(root) {
  const r = spawnSync('git', ['-c', 'core.quotepath=false', 'ls-files', '--cached', '--others', '--exclude-standard'], { cwd: root, encoding: 'utf8', windowsHide: true, maxBuffer: 64 * 1024 * 1024 })
  if (r.status !== 0) return []
  return [...new Set(r.stdout.split('\n').map((x) => x.trim().replace(/\\/g, '/')).filter(Boolean))].sort(byName)
}

const familiesSection = {
  id: 'families',
  title: 'Families',
  build({ root, config }) {
    const reg = readRegistryFile(root, config.registry)
    if (!reg || !reg.families.length) return []
    const items = [...reg.families].sort((a, b) => byName(a.id, b.id)).map((f) => [`\`${f.id}\``, f.selector, f.when].filter(Boolean).join(' · '))
    return [{ items, pack: false }]
  },
}

const engineSection = {
  id: 'engine',
  title: 'Engine classes',
  build({ root, config }) {
    const prefix = config.enginePrefix
    const file = config.globalStylesheet
    if (!prefix || !file || !existsSync(join(root, file))) return []
    const esc = prefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    const re = new RegExp(`(?<![\\w-])\\.(${esc}[\\w-]*)`, 'g')
    const names = new Set()
    for (const m of readFileSync(join(root, file), 'utf8').matchAll(re)) names.add(m[1])
    return names.size ? [{ items: [...names].sort(byName).map((n) => `\`.${n}\``), pack: true }] : []
  },
}

const tokensSection = {
  id: 'tokens',
  title: 'Tokens',
  build({ root, config }) {
    const kinds = Object.entries(config.tokenKinds ?? {}).filter(([, p]) => p)
    const globs = (config.tokenFiles ?? []).filter(Boolean)
    if (!kinds.length || !globs.length) return []
    const isToken = picomatch(globs, { dot: true })
    const found = new Map(kinds.map(([k]) => [k, new Set()]))
    for (const f of repoFiles(root).filter((p) => isToken(p))) {
      for (const line of readFileSync(join(root, f), 'utf8').split(/\r?\n/)) {
        const m = /^\s*((?:--|\$|@)[\w-]+)\s*:/.exec(line)
        if (!m) continue
        for (const [k, p] of kinds) if (m[1].startsWith(p)) found.get(k).add(m[1])
      }
    }
    return kinds.filter(([k]) => found.get(k).size).map(([k]) => ({ heading: k, items: [...found.get(k)].sort(byName).map((n) => `\`${n}\``), pack: true }))
  },
}

const defaultsSection = {
  id: 'defaults',
  title: 'Defaults (on)',
  build({ root, config }) {
    const c = readContract(root, config.defaults)
    if (!c || c.errors.length) return []
    return [{ items: onLines(c.entries), pack: false }]
  },
}

/** The sections in order. A later plan appends its own. */
export const sections = [familiesSection, engineSection, tokensSection, defaultsSection]

function packLines(items) {
  const lines = []
  let cur = ''
  for (const it of items) {
    if (cur && cur.length + 1 + it.length > WIDTH) { lines.push(cur); cur = it } else cur = cur ? `${cur} ${it}` : it
  }
  if (cur) lines.push(cur)
  return lines
}

/** The block's lines when it may use `cap` lines: every item, or fewer items and a final `+N more`. */
function fit(block, cap) {
  const render = (items) => (block.pack ? packLines(items) : items.map((i) => `- ${i}`))
  const full = render(block.items)
  if (full.length <= cap) return full
  let n = block.items.length
  while (n > 0 && render(block.items.slice(0, n)).length + 1 > cap) n--
  return [...render(block.items.slice(0, n)), `+${block.items.length - n} more`]
}

/** The inventory text for a repo. */
export function buildInventory(root, over = {}, list = sections) {
  const config = inventoryConfig(over)
  const ctx = { root, config }
  const parts = []
  for (const s of list) {
    const blocks = s.build(ctx).filter((b) => b.items.length)
    if (blocks.length) parts.push({ title: s.title, blocks })
  }
  const all = parts.flatMap((p) => p.blocks)
  let fixed = HEADER.length
  for (const p of parts) fixed += 2 + p.blocks.filter((b) => b.heading).length // blank + `## title`, and a `### kind` each
  let room = MAX_LINES - 2 - fixed
  const caps = new Map()
  const order = [...all].sort((a, b) => fit(a, Infinity).length - fit(b, Infinity).length)
  order.forEach((b, i) => {
    const need = fit(b, Infinity).length
    const cap = Math.max(2, Math.min(need, Math.floor(room / (order.length - i))))
    caps.set(b, cap)
    room -= Math.min(need, cap)
  })
  const out = [...HEADER]
  for (const p of parts) {
    out.push('', `## ${p.title}`)
    for (const b of p.blocks) {
      if (b.heading) out.push(`### ${b.heading}`)
      out.push(...fit(b, caps.get(b)))
    }
  }
  return `${out.join('\n')}\n`
}

/** { ok, expected, actual } — actual is null when the file is missing. */
export function checkInventory(root, over = {}) {
  const config = inventoryConfig(over)
  const expected = buildInventory(root, over)
  const file = join(root, config.path)
  const actual = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null
  return { ok: actual === expected, expected, actual, path: config.path }
}

export const STALE = 'INVENTORY: stale — run node scripts/inventory.mjs'

export function main(argv = process.argv.slice(2), root = process.cwd(), print = (l) => console.log(l)) {
  let over = {}
  const check = argv.includes('--check')
  const ci = argv.findIndex((a) => a === '--config' || a.startsWith('--config='))
  if (ci >= 0) {
    const file = argv[ci].includes('=') ? argv[ci].slice(9) : argv[ci + 1]
    if (!file) {
      print('INVENTORY: refused — --config needs a file')
      return 2
    }
    over = JSON.parse(readFileSync(join(root, file), 'utf8'))
  }
  if (check) {
    const r = checkInventory(root, over)
    print(r.ok ? 'INVENTORY: ok' : STALE)
    return r.ok ? 0 : 1
  }
  const config = inventoryConfig(over)
  const text = buildInventory(root, over)
  mkdirSync(dirname(join(root, config.path)), { recursive: true })
  writeFileSync(join(root, config.path), text)
  print(`INVENTORY: written ${config.path} (${text.split('\n').length - 1} lines)`)
  return 0
}

function isEntry(metaUrl) {
  if (!process.argv[1]) return false
  try {
    return realpathSync(fileURLToPath(metaUrl)) === realpathSync(process.argv[1])
  } catch {
    return false
  }
}

if (isEntry(import.meta.url)) process.exitCode = main()
